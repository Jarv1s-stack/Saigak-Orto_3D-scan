import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, extname, join, resolve } from "node:path";
import { parseStl, measureScan } from "../lib/cranio.mjs";
import { FEATURE_COLUMNS, TARGET_COLUMNS } from "./model.mjs";

function parseArgs(argv) {
  const options = { scale: 1, slice: 0.5, angle: 30, output: "data/pseudo-landmarks.csv" };
  for (let index = 0; index < argv.length; index += 1) {
    const key = argv[index];
    if (key === "--input-dir") options.inputDir = argv[++index];
    else if (key === "--output") options.output = argv[++index];
    else if (key === "--scale") options.scale = Number(argv[++index]);
    else if (key === "--slice") options.slice = Number(argv[++index]);
    else if (key === "--angle") options.angle = Number(argv[++index]);
    else throw new Error(`Unknown option: ${key}`);
  }
  if (!options.inputDir) throw new Error("Usage: node ml/prepare-pseudo-labels.mjs --input-dir <folder-with-stl> [--output data/pseudo-landmarks.csv] [--scale 1] [--slice 0.5] [--angle 30]");
  if (!Number.isFinite(options.scale) || options.scale < 0.001 || options.scale > 100000) throw new Error("--scale must be between 0.001 and 100000.");
  if (!Number.isFinite(options.slice) || options.slice < 0.1 || options.slice > 0.9) throw new Error("--slice must be between 0.1 and 0.9.");
  if (!Number.isFinite(options.angle) || options.angle < 15 || options.angle > 45) throw new Error("--angle must be between 15 and 45 degrees.");
  return options;
}

async function findStlFiles(directory) {
  const found = [];
  async function walk(current) {
    for (const entry of await readdir(current, { withFileTypes: true })) {
      const full = join(current, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile() && extname(entry.name).toLowerCase() === ".stl") found.push(full);
    }
  }
  await walk(directory);
  return found.sort((first, second) => first.localeCompare(second));
}

function csvNumber(value) {
  if (!Number.isFinite(value)) throw new Error("A generated feature or landmark is not finite.");
  return Number(value.toFixed(8)).toString();
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const inputDir = resolve(options.inputDir);
  const outputPath = resolve(options.output);
  const files = await findStlFiles(inputDir);
  if (files.length === 0) throw new Error(`No STL files found in: ${inputDir}`);

  const header = ["scan_code", ...FEATURE_COLUMNS, ...TARGET_COLUMNS];
  const lines = [header.join(",")];
  const skipped = [];

  for (let index = 0; index < files.length; index += 1) {
    const file = files[index];
    try {
      const mesh = parseStl(await readFile(file));
      const metrics = measureScan(mesh, {
        scaleMmPerUnit: options.scale,
        sliceFraction: options.slice,
        diagonalDegrees: options.angle,
      });
      // Use the exact full-resolution profile created by measurement, not the
      // downsampled contour sent to the browser for display.
      const { features, center, maxRadius } = metrics.mlFeatureProfile;
      const endpoints = metrics.diagonals.flat();
      if (features.length !== FEATURE_COLUMNS.length || endpoints.length !== 4 || !Number.isFinite(maxRadius) || maxRadius <= 0) {
        throw new Error("Could not derive the complete feature vector and four diagonal endpoints.");
      }
      const targets = endpoints.flatMap(([x, y]) => [(x - center[0]) / maxRadius, (y - center[1]) / maxRadius]);
      const code = `pseudo_${String(index + 1).padStart(4, "0")}`;
      lines.push([code, ...features.map(csvNumber), ...targets.map(csvNumber)].join(","));
      console.log(`OK ${code}`);
    } catch (error) {
      skipped.push({ file, reason: error.message });
      console.error(`SKIP ${file}: ${error.message}`);
    }
  }

  if (lines.length === 1) throw new Error("No usable STL scans were processed.");
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, `${lines.join("\n")}\n`, "utf8");
  console.log(`\nCSV saved: ${outputPath}`);
  console.log(`Usable scans: ${lines.length - 1}; skipped: ${skipped.length}`);
  console.log("IMPORTANT: targets are pseudo-labels generated by the deterministic geometry algorithm, NOT independent clinician annotations.");
  console.log("This dataset can verify the ML software pipeline only. Its held-out MAE is not clinical accuracy or independent validation.");
  if (lines.length - 1 < 12) {
    console.error(`Only ${lines.length - 1} usable STL files. The trainer requires at least 12 unique scan codes.`);
    process.exitCode = 2;
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
